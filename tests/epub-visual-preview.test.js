"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const preview=require("../epub-visual-preview.js");
const xml='<?xml version="1.0"?><!DOCTYPE html><html xmlns="http://www.w3.org/1999/xhtml"><head><meta charset="utf-8"/><title>Test</title><link rel="stylesheet" type="text/css" href="style.css"/></head><body><section epub:type="chapter"><h1>Chapter 1</h1><p id="p-1-1">First <em>italic</em> sentence.</p><div class="message-group outgoing" data-opal-message="outgoing"><span class="message-sender" data-opal-narration="skip">Lily</span><p class="message-bubble">Okay!</p></div><p class="scene-break illustrated" data-opal-scene-break="true"><img src="images/scene-ornament.png" alt="" role="presentation"/></p></section></body></html>';
const css='h1{text-align:center}em{font-style:italic}.message-bubble{background:#d2e0f1}';
const picture='data:image/png;base64,aGVsbG8=';
const actual=preview.htmlDocument(xml,css,{"images/scene-ornament.png":picture});
assert.ok(actual.startsWith("<!DOCTYPE html>"));
assert.ok(actual.includes("<style>"+css+"</style>"));
assert.ok(actual.includes('Content-Security-Policy'));
assert.ok(!actual.includes('<link rel="stylesheet"'),"external stylesheet must not be requested");
assert.ok(actual.includes('src="'+picture+'"'),"packaged illustration should display");
assert.ok(actual.includes('<em>italic</em>'));
assert.ok(actual.includes('class="message-group outgoing"'));
assert.ok(actual.includes('data-opal-scene-break="true"'));
assert.ok(!actual.includes("<?xml"),"srcdoc is an HTML document, not XML prolog");
const info=preview.inspectXhtml(xml);
assert.deepEqual({...info,warnings:[]},{headingCount:1,paragraphs:3,italics:1,groups:1,sceneBreaks:1,illustrations:1,warnings:[]});
assert.deepEqual(preview.inspectXhtml("<html><head></head><body><section></section></body></html>").warnings,["This section has no body paragraphs."]);
assert.ok(preview.inspectXhtml('<html><head></head><body><p>[[i]]oops</p></body></html>').warnings[0].includes("italic"));
const unauthorized=preview.htmlDocument(xml.replace('images/scene-ornament.png','https://example.invalid/t.png'),css,{});
assert.ok(unauthorized.includes('<img src=""'),"unpackaged images cannot fetch external resources");
assert.throws(()=>preview.htmlDocument("<body>partial</body>",css),/incomplete/);
const html=fs.readFileSync(path.join(__dirname,"..","index.html"),"utf8");
const main=fs.readFileSync(path.join(__dirname,"..","script.js"),"utf8");
const sw=fs.readFileSync(path.join(__dirname,"..","sw.js"),"utf8");
const loader=fs.readFileSync(path.join(__dirname,"..","script-loader.js"),"utf8");
for(const id of ["epubPreviewBtn","epubPreviewDialog","epubPreviewClose","epubPreviewSelect","epubPreviewPrev","epubPreviewNext","epubPreviewViewport","epubPreviewFrame","epubPreviewMetrics","epubPreviewStatus"])
  assert.ok(html.includes('id="'+id+'"'),"missing preview UI: "+id);
assert.ok(html.includes('id="epubPreviewFrame" title="Generated EPUB chapter preview" sandbox=""'),"iframe must block script execution and same-origin access");
assert.ok(html.includes("epub-visual-preview.js?v=262"));
assert.ok(sw.includes("./epub-visual-preview.js?v=262"));
const revision=loader.match(/script\.js\?v=([0-9]+)/);
assert.ok(revision && Number(revision[1])>=262,"EPUB preview requires loader 262+");
const current=main.match(/const BUILD_VERSION = "([0-9]+)"/);
assert.ok(current && Number(current[1])>=262,"EPUB preview requires Build 262+");
assert.ok(main.includes('async function buildEpub({preview=false} = {})'));
assert.ok(main.includes('if(preview)return blob;'),"preview should not download the archive");
assert.ok(main.includes('await buildEpub({preview:true})'));
assert.ok(main.includes('window.JSZip.loadAsync(blob)'),"render the packaged EPUB rather than duplicate rendering logic");
assert.ok(main.includes('if (!preview) {') && main.includes('ensureItalicEvidenceProjected();'),"read-only preview must avoid projection side effects");
assert.ok(main.includes('if(els.epubPreviewFrame)els.epubPreviewFrame.srcdoc=""'),"closing preview should release document");
console.log("Build 262 EPUB visual preview: archive-based rendering, navigation, sandbox and regression checks passed");
